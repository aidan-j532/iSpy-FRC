def print_summary(results: SuiteResults):
    section("SUMMARY")

    rows = [
        ("Correctness (vs .pt)", results.correctness.get("status", "SKIP")),
        ("Accuracy (val set)", results.accuracy.get("status", "SKIP")),
        ("Quant layer analysis", results.quant_analysis.get("status", "SKIP")),
        ("Speed", results.speed.get("status", "SKIP")),
        ("Stability (long-run)", results.stability.get("status", "SKIP")),
        ("Edge cases", results.edge_cases.get("status", "SKIP")),
    ]
    for label, status in rows:
        subline(label, "", status)

    hard_fails = [label for label, status in rows if status == "FAIL"]
    ran = [status for _, status in rows if status != "SKIP"]

    print()
    if not ran:
        verdict = "INCONCLUSIVE"
        reasons = ["No sections ran - provide --images/--val-dir/--onnx/--sample-image as needed."]
    elif hard_fails:
        verdict = "NOT READY"
        reasons = [f"Failing section(s): {', '.join(hard_fails)}"]
    elif any(status == "SKIP" for _, status in rows):
        verdict = "PARTIALLY VALIDATED"
        skipped = [label for label, status in rows if status == "SKIP"]
        reasons = [f"Skipped (missing inputs): {', '.join(skipped)}"]
    else:
        verdict = "READY"
        reasons = ["All sections passed."]

    color = {"READY": C.GREEN, "PARTIALLY VALIDATED": C.YELLOW,
             "NOT READY": C.RED, "INCONCLUSIVE": C.DIM}[verdict]
    print(_c(f"  VERDICT: {verdict}", C.BOLD + color))
    for r in reasons:
        print(f"    - {r}")
    print()

    results.overall_verdict = verdict
    results.verdict_reasons = reasons


def save_json_report(results: SuiteResults, out_path: Path):
    def _clean(obj):
        if isinstance(obj, dict):
            return {k: _clean(v) for k, v in obj.items()}
        if isinstance(obj, list):
            return [_clean(v) for v in obj]
        if isinstance(obj, (np.floating,)):
            return float(obj)
        if isinstance(obj, (np.integer,)):
            return int(obj)
        if isinstance(obj, tuple):
            return [_clean(v) for v in obj]
        return obj

    payload = _clean({
        "overall_verdict": results.overall_verdict,
        "verdict_reasons": results.verdict_reasons,
        "correctness": results.correctness,
        "accuracy": results.accuracy,
        "quant_analysis": results.quant_analysis,
        "speed": results.speed,
        "stability": results.stability,
        "edge_cases": results.edge_cases,
    })
    out_path.parent.mkdir(parents=True, exist_ok=True)
    with open(out_path, "w") as f:
        json.dump(payload, f, indent=2)
    print(f"  Full report saved to {out_path}\n")


# ─── CLI ──────────────────────────────────────────────────────────────────────

def _build_config(file_path: str, extra: dict | None = None) -> dict:
    cfg = {"file_path": file_path}
    if extra:
        cfg.update(extra)
    return cfg


def main():
    parser = argparse.ArgumentParser(description="Full RKNN NPU validation suite")
    parser.add_argument("--rknn", required=True, help="Path to .rknn model")
    parser.add_argument("--pt", default=None, help="Path to source .pt model (for correctness check)")
    parser.add_argument("--onnx", default=None, help="Path to intermediate .onnx (for quant analysis)")
    parser.add_argument("--images", nargs="*", default=None, help="Explicit test images for correctness check")
    parser.add_argument("--val-dir", default=None,
                         help="Dir with images/ + labels/ (YOLO txt format) for accuracy check")
    parser.add_argument("--dataset-txt", default=None, help="RKNN calibration dataset.txt")
    parser.add_argument("--sample-image", default=None, help="Single image for accuracy_analysis()")
    parser.add_argument("--input-size", type=int, nargs=2, default=[640, 640])
    parser.add_argument("--duration", type=float, default=5.0, help="Speed-test duration (s) per core mask")
    parser.add_argument("--stability-duration", type=float, default=0.0,
                         help="Stability-test duration (s), 0 = skip")
    parser.add_argument("--output", default=str(_PROJECT_ROOT / "Outputs" / "rknn_test_report.json"))
    parser.add_argument("--skip", nargs="*", default=[],
                         choices=["correctness", "accuracy", "quant", "speed", "stability", "edge"],
                         help="Sections to skip")
    args = parser.parse_args()

    print(_c("\n  iSpy RKNN NPU Validation Suite", C.BOLD))
    print(_c(f"  Model: {args.rknn}\n", C.DIM))

    rknn_config = _build_config(args.rknn)
    results = SuiteResults()

    # Correctness
    if "correctness" not in args.skip:
        images = [Path(p) for p in args.images] if args.images else []
        if args.val_dir and not images:
            vd = Path(args.val_dir) / "images"
            if vd.exists():
                images = sorted(vd.glob("*.jpg")) + sorted(vd.glob("*.png"))
                images = images[:20]  # cap for runtime
        if args.pt and images:
            pt_config = _build_config(args.pt)
            run_correctness(pt_config, rknn_config, images, results)
        else:
            section("1. CORRECTNESS  -  .rknn vs .pt box agreement")
            skip("requires both --pt and (--images or --val-dir)")
            results.correctness["status"] = "SKIP"
    else:
        results.correctness["status"] = "SKIP"

    # Accuracy
    if "accuracy" not in args.skip:
        val_dir = Path(args.val_dir) if args.val_dir else None
        run_accuracy(rknn_config, val_dir, results)
    else:
        results.accuracy["status"] = "SKIP"

    # Quant analysis
    if "quant" not in args.skip:
        onnx_path = Path(args.onnx) if args.onnx else None
        dataset_txt = Path(args.dataset_txt) if args.dataset_txt else None
        sample_image = Path(args.sample_image) if args.sample_image else None
        if sample_image is None and args.val_dir:
            vd = Path(args.val_dir) / "images"
            found = sorted(vd.glob("*.jpg")) + sorted(vd.glob("*.png")) if vd.exists() else []
            sample_image = found[0] if found else None
        run_quant_analysis(
            onnx_path, tuple(args.input_size), dataset_txt, sample_image,
            _PROJECT_ROOT / "Outputs", results,
        )
    else:
        results.quant_analysis["status"] = "SKIP"

    # Speed
    if "speed" not in args.skip:
        run_speed(rknn_config, args.duration, results)
    else:
        results.speed["status"] = "SKIP"

    # Stability
    if "stability" not in args.skip and args.stability_duration > 0:
        run_stability(rknn_config, args.stability_duration, results)
    else:
        section("5. STABILITY  -  long-run FPS drift + thermal")
        skip("--stability-duration not set (>0 required) or --skip stability passed")
        results.stability["status"] = "SKIP"

    # Edge cases
    if "edge" not in args.skip:
        run_edge_cases(rknn_config, tuple(args.input_size), results)
    else:
        results.edge_cases["status"] = "SKIP"

    print_summary(results)
    save_json_report(results, Path(args.output))

    return 0 if results.overall_verdict in ("READY", "PARTIALLY VALIDATED") else 1


if __name__ == "__main__":
    sys.exit(main())