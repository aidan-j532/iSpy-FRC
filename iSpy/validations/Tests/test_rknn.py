def run_edge_cases(rknn_config, input_size, results: SuiteResults):
    section("6. EDGE CASES  -  empty frame, corners, overlaps")

    from iSpy.vision.genericYolo import GenericYolo
    try:
        model = GenericYolo(rknn_config, core_mask=7)
    except Exception as e:
        warn(f"Could not load .rknn model: {e}")
        results.edge_cases["status"] = "SKIP"
        return

    checks = []

    # 6a. Empty / blank frame - should not crash, should return 0 or near-0 boxes
    try:
        blank = np.full((480, 640, 3), 20, dtype=np.uint8)
        res = model.predict(blank, orig_shape=blank.shape)
        ok = res is not None and isinstance(res.boxes, list)
        checks.append(("Blank frame handled without crash", ok))
    except Exception as e:
        checks.append((f"Blank frame handled without crash (raised: {e})", False))

    # 6b. Solid noise frame - should not produce absurd box counts
    try:
        noise = np.random.randint(0, 256, (480, 640, 3), dtype=np.uint8)
        res = model.predict(noise, orig_shape=noise.shape)
        ok = len(res.boxes) < 50  # sanity ceiling, not a real detector should never do this
        checks.append((f"Noise frame doesn't explode box count ({len(res.boxes)} boxes)", ok))
    except Exception as e:
        checks.append((f"Noise frame handled without crash (raised: {e})", False))

    # 6c. All-black frame
    try:
        black = np.zeros((480, 640, 3), dtype=np.uint8)
        res = model.predict(black, orig_shape=black.shape)
        ok = res is not None
        checks.append(("All-black frame handled without crash", ok))
    except Exception as e:
        checks.append((f"All-black frame handled without crash (raised: {e})", False))

    # 6d. Non-square / unusual aspect ratio input
    try:
        wide = np.full((240, 1280, 3), 40, dtype=np.uint8)
        res = model.predict(wide, orig_shape=wide.shape)
        boxes_in_bounds = all(
            0 <= b.xyxy[0] <= wide.shape[1] and 0 <= b.xyxy[2] <= wide.shape[1]
            and 0 <= b.xyxy[1] <= wide.shape[0] and 0 <= b.xyxy[3] <= wide.shape[0]
            for b in res.boxes
        )
        checks.append(("Wide-aspect frame: boxes stay within image bounds", boxes_in_bounds))
    except Exception as e:
        checks.append((f"Wide-aspect frame handled without crash (raised: {e})", False))

    for label, ok in checks:
        subline(label, "", "PASS" if ok else "FAIL")

    passed = sum(1 for _, ok in checks if ok)
    results.edge_cases = {
        "status": "PASS" if passed == len(checks) else "FAIL",
        "passed": passed,
        "total": len(checks),
        "checks": [{"label": l, "passed": ok} for l, ok in checks],
    }

    try:
        model.release()
    except Exception:
        pass


