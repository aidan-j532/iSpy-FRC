def _expected_fps_for(devices_name: str) -> float:
    name = str(devices_name or "").lower()

    for key, fps in devices_expected_fps.items():
        if key in name:
            return float(fps)

    return 0.0

def get_expected_inf_ms(devices_name: str) -> dict:
    """DISCLAMER: AI generated, cause the old default was the wrong type"""
    fps = _expected_fps_for(devices_name)
    return {"expected_inf_ms": 1000.0 / fps if fps > 0 else 0.0}

def _os_release() -> dict:
    """DISCLAMER: Generated by AI due to complexity"""
    getter = getattr(platform, "freedesktop_os_release", None)

    if getter is not None:
        try:
            return getter()
        except Exception:
            pass

    try:
        release = {}
        with open("/etc/os-release", "r", encoding="utf-8", errors="ignore") as f:
            for line in f:
                if "=" not in line or line.startswith("#"):
                    continue
                key, value = line.rstrip("\n").split("=", 1)
                release[key.strip()] = value.strip().strip('"')
        return release
    except OSError:
        return {}

def get_os_name() -> str:
    system = platform.system() or ""

    if system == "Linux":
        return _os_release().get("NAME") or "Linux"

    if system == "Darwin":
        return "macOS"

    return system or "Unknown"

def get_os_version() -> str:
    """DISCLAMER: Generated by AI due to complexity"""
    system = platform.system() or ""

    if system == "Linux":
        return _os_release().get("VERSION_ID") or platform.release() or "Unknown"

    if system == "Darwin":
        return platform.mac_ver()[0] or platform.release() or "Unknown"

    if system == "Windows":
        try:
            win = platform.win32_ver()
            version = win[1] if len(win) > 1 else ""

            # Windows 11 still reports a 10.x version; the build gives it away.
            parts = version.split(".")
            if len(parts) >= 3 and parts[2].isdigit() and int(parts[2]) >= 22000:
                return "11 (build %s)" % parts[2]

            if version:
                return version
        except Exception:
            pass

        return platform.release() or "Unknown"

    return platform.version() or "Unknown"

def get_architecture() -> str:
    """DISCLAMER: Generated by AI due to complexity"""
    machine = platform.machine() or ""
    aliases = {
        "x86_64": "x64",
        "amd64": "x64",
        "aarch64": "arm64",
        "arm64": "arm64",
        "i386": "x86",
        "i486": "x86",
        "i586": "x86",
        "i686": "x86",
    }
    label = aliases.get(machine.lower(), machine) or "Unknown"
    bits = platform.architecture()[0]

    return f"{label} ({bits})" if bits else label

def get_python_version() -> str:
    return platform.python_version() or "Unknown"

def get_supported_backends() -> list:
    """DISCLAMER: Generated by AI due to complexity"""
    formats = globals().get("SUPPORTED_FORMATS") or ()
    return sorted(str(fmt) for fmt in formats if fmt)

def get_formatted_description() -> str:
    """DISCLAMER: Generated by AI due to complexity"""
    device_name = get_device_model() or "Unknown"

    # CPU information
    cpu_info = clean_cpu_name(get_raw_cpu_name() or "") or "Unknown"

    # Accelerator information (GPU, NPU, etc.)
    try:
        accelerator_type = recommend_format() or "unknown"
    except Exception:
        accelerator_type = "unknown"
    accelerator_name = get_accelerators_name_from_type(accelerator_type) or "Unknown"

    # Memory, Hard drive
    ram_total = get_ram() or "Unknown"
    storage_total = get_total_storage() or "Unknown"

    # Platform
    os_name = get_os_name()
    os_version = get_os_version()
    architecture = get_architecture()

    # Software
    python_version = get_python_version()
    supported_backends = ", ".join(get_supported_backends()) or "Unknown"

    expected_fps = _expected_fps_for(device_name)
    expected_inf_ms = 1000.0 / expected_fps if expected_fps > 0 else 0.0

    return "\n".join(
        [
            f"Device: {device_name}",
            f"CPU: {cpu_info}",
            f"Accelerator ({accelerator_type}): {accelerator_name}",
            f"Memory: {ram_total}",
            f"Storage: {storage_total}",
            f"OS: {os_name} {os_version}".rstrip(),
            f"Architecture: {architecture}",
            f"Python: {python_version}",
            f"Backends: {supported_backends}",
            f"Expected FPS: {expected_fps:.1f}" if expected_fps else "Expected FPS: Unknown",
            f"Expected inference: {expected_inf_ms:.2f} ms" if expected_inf_ms else "Expected inference: Unknown",
        ]
    )

def get_total_storage():
    """DISCLAMER: Generated by AI due to complexity"""
    # Gets all storage, including built-in, all partitions, USB, etc.
    gb = 1024 ** 3
    seen = set()
    total = 0.0

    for partition in psutil.disk_partitions():
        key = partition.device or partition.mountpoint

        if key in seen:
            continue

        seen.add(key)

        try:
            usage = psutil.disk_usage(partition.mountpoint)
        except (PermissionError, OSError):
            # Skips bad drives/unready drives.
            continue

        if usage.total > 0:
            total += usage.total

    return f"{total / gb:.2f} GB" if total else "Unknown"

def get_ram():
    # I made this one :) (cause its a LOT simplier)
    mem = psutil.virtual_memory()

    total_gb = mem.total / (1024 ** 3)

    return f"{total_gb:.2f} GB"

def get_accelerators_name_from_type(accelerator_type: str) -> str:
    """DISCLAMER: Generated by AI due to complexity"""
    system = platform.system()

    # Linux
    if system == "Linux":
        # Rockchip SoCs (Orange Pi, etc.)
        try:
            paths = [
                "/proc/device-tree/compatible",
                "/sys/firmware/devicetree/base/compatible",
            ]

            for path in paths:
                if os.path.exists(path):
                    with open(path, "rb") as f:
                        compatible = f.read().decode(errors="ignore")

                    match = re.search(r"rk\d+", compatible, re.IGNORECASE)
                    if match:
                        return f"Rockchip {match.group().upper()}"
        except OSError:
            pass

        # NVIDIA / AMD / Intel GPUs
        try:
            output = subprocess.check_output(
                ["lspci"],
                stderr=subprocess.DEVNULL,
                text=True,
                errors="ignore",
            )

            for line in output.splitlines():
                if not re.search(
                    r"VGA compatible controller|3D controller|Display controller",
                    line,
                    re.IGNORECASE,
                ):
                    continue

                name = line.split(":", 2)[-1].strip()

                # Remove PCI revision information
                name = re.sub(r"\s*\(rev [^)]+\)", "", name)

                return name

        except (OSError, subprocess.SubprocessError, UnicodeError):
            pass

    # Windows
    elif system == "Windows":
        try:
            cmd = [
                "powershell",
                "-NoProfile",
                "-Command",
                "Get-CimInstance Win32_VideoController | Select-Object -ExpandProperty Name",
            ]

            output = subprocess.check_output(
                cmd,
                stderr=subprocess.DEVNULL,
                text=True,
                errors="ignore",
            ).strip()

            if output:
                return output.splitlines()[0].strip()

        except (OSError, subprocess.SubprocessError, UnicodeError):
            pass

    # macOS
    elif system == "Darwin":
        try:
            output = subprocess.check_output(
                ["sysctl", "-n", "machdep.cpu.brand_string"],
                stderr=subprocess.DEVNULL,
                text=True,
                errors="ignore",
            ).strip()

            if output:
                match = re.search(r"Apple M\d+(?: Pro| Max| Ultra)?", output)
                if match:
                    return match.group()

        except (OSError, subprocess.SubprocessError, UnicodeError):
            pass

    return "Unknown"

def get_raw_cpu_name():
    """DISCLAMER: Generated by AI due to complexity"""
    system = platform.system()

    if system == "Windows":
        try:
            cmd = [
                "powershell",
                "-NoProfile",
                "-Command",
                "(Get-CimInstance Win32_Processor).Name",
            ]
            output = subprocess.check_output(
                cmd,
                stderr=subprocess.DEVNULL,
                text=True,
                errors="ignore",
            ).strip()
            if output:
                return output.splitlines()[0].strip()
        except (OSError, subprocess.SubprocessError, UnicodeError):
            pass

    elif system == "Linux":
        try:
            with open("/proc/cpuinfo", "r", encoding="utf-8", errors="ignore") as f:
                for line in f:
                    if line.startswith(("model name", "Model", "Processor")):
                        return line.split(":", 1)[1].strip()
        except OSError:
            pass

    elif system == "Darwin":
        try:
            output = subprocess.check_output(
                ["sysctl", "-n", "machdep.cpu.brand_string"],
                stderr=subprocess.DEVNULL,
                text=True,
                errors="ignore",
            ).strip()
            if output:
                return output
        except (OSError, subprocess.SubprocessError, UnicodeError):
            pass

    return platform.processor() or platform.machine() or "Unknown"


def clean_cpu_name(raw_name):
    """DISCLMAER: AI generated, cause Regex is hard"""
    # 1. Remove trademark symbols like (R), (TM), (C)
    name = re.sub(r"\((R|TM|C)\)", "", raw_name, flags=re.IGNORECASE)

    # 2. Remove clock speed and everything after '@' (e.g., "@ 3.80GHz")
    name = name.split("@")[0]

    # 3. Remove common filler words
    name = re.sub(
        r"\b(CPU|Processor|with Radeon Graphics|rev \d+|\(v\w+\))\b",
        "",
        name,
        flags=re.IGNORECASE,
    )

    # 4. Shorten specific chip families to clean labels
    # Turns "Intel Core i7-10700K" -> "Intel Core i7"
    intel_match = re.search(r"(Intel Core i[3579])", name, re.IGNORECASE)
    if intel_match:
        return intel_match.group(1)

    # Turns "AMD Ryzen 7 5800X" -> "AMD Ryzen 7"
    amd_match = re.search(r"(AMD Ryzen [3579])", name, re.IGNORECASE)
    if amd_match:
        return amd_match.group(1)

    # Turns "ARMv7 rev 3" -> "ARMv7"
    arm_match = re.search(r"(ARMv\d+)", name, re.IGNORECASE)
    if arm_match:
        return arm_match.group(1)

    # 5. Clean up extra spaces for any other CPUs (e.g., Xeon, Celeron, Apple, etc.)
    return re.sub(r"\s+", " ", name).strip()

def get_device_model() -> str:
    """DISCLAMER: Generated by AI due to complexity"""
    system = platform.system()
    placeholders = {
        "system product name",
        "to be filled by o.e.m.",
        "default string",
        "standard",
        "unknown",
    }

    if system == "Linux":
        # ARM devices
        dt_model = "/proc/device-tree/model"
        if os.path.exists(dt_model):
            try:
                with open(dt_model, "r", encoding="utf-8", errors="ignore") as f:
                    # Device tree strings often end with a null byte (\x00) (apparently)
                    model = f.read().strip("\x00\n\r ")
                    if model and model.lower() not in placeholders:
                        return model
            except OSError:
                pass

        # x86 / generic Linux
        dmi_paths = [
            "/sys/devices/virtual/dmi/id/product_name",
            "/sys/devices/virtual/dmi/id/board_name",
        ]
        for path in dmi_paths:
            if os.path.exists(path):
                try:
                    with open(path, "r", encoding="utf-8", errors="ignore") as f:
                        model = f.read().strip()
                        # Filter out generic placeholder values from custom/unbranded BIOS
                        if model and model.lower() not in placeholders:
                            return model
                except OSError:
                    pass

    elif system == "Windows":
        # Windows CIM/WMI
        try:
            cmd = [
                "powershell",
                "-NoProfile",
                "-Command",
                "(Get-CimInstance -ClassName Win32_ComputerSystem).Model",
            ]
            output = subprocess.check_output(
                cmd,
                stderr=subprocess.DEVNULL,
                text=True,
                errors="ignore",
            ).strip()
            model = output.splitlines()[0].strip() if output else ""

            if model and model.lower() not in placeholders:
                return model
        except (OSError, subprocess.SubprocessError, UnicodeError):
            pass

    elif system == "Darwin":
        # Apple hardware: hw.model gives e.g. "Mac14,2".
        try:
            output = subprocess.check_output(
                ["sysctl", "-n", "hw.model"],
                stderr=subprocess.DEVNULL,
                text=True,
                errors="ignore",
            ).strip()
            if output:
                return output
        except (OSError, subprocess.SubprocessError, UnicodeError):
            pass

    # Fallback to network hostname
    return platform.node() or "Unknown"


